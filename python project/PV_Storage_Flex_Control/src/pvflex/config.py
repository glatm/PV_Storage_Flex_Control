# =============================================================================
# config.py  ——  整个工程的“配置中心”（新手改参数只需要看这一个文件）
# -----------------------------------------------------------------------------
# 【这个文件解决什么问题】
#   把整个工程里"经常要改、且跟着项目走"的东西集中放在一起：
#     1) 数据文件放在哪个文件夹（路径）
#     2) 几个算指标必须用、但原始数据里没有的"假设参数"
#        （光伏装机多少 kW、电池多大、电价多少、碳排放因子多少……）
#
# 【为什么要把这些单独放一个文件】
#   好处：以后你换数据、改参数，不用在十几个文件里到处翻，只改这一个文件就行。
#         这就是"配置和代码分开"的基本思想 —— 代码负责"怎么算"，
#         配置负责"用哪些数"，两者分开以后，同一份代码配不同参数就能复用到别的项目。
#
# 【怎么用】
#   别的文件里写 `import pvflex.config as cfg`，然后用 `cfg.PV_RATED_KW`
#   这种写法就能拿到这里的值。你不用管细节，知道"改这里就能改全局"即可。
#
# 【⚠️ 改完参数后必须做的事】
#   改完 BATTERY_CAPACITY_KWH / PV_RATED_KW 这类关键参数后，务必重跑
#   `python -m pvflex.cli` 确认没报错，并把新数字同步到论文/报告里。
#   参数和结论是一一对应的 —— 忘了同步就会出现"论文写 1000kWh、
#   代码其实按 2000kWh 跑"这种致命的不一致。
