# ---- 3.0 直流电压等级序列（申报书十一(一)2、技术关键(2)）----
# 申报书要求“确定最优的直流电压等级序列”，本项目直流微电网采用双电压等级：
#   · 700V 直流母线：厂内动力、大功率负载（如空调变频驱动、动力设备）主干；
#   · 48V  直流母线：照明、小型节能负载、低压直流终端（对应 Simulink 48V 子系统）。
# 这两个值与 MATLAB/Simulink 主模型 PV_Microgrid_700V.slx 的双电压架构保持一致。
# 下面仅作“工程口径记录”，供优化/仿真模块引用；若设计院最终定稿有变，改这里即可。
#
# 【为什么直流微电网要分两个电压等级？】
#   用同一个电压供所有负载很不划算：
#     电压太高 → 照明这类小功率设备要额外降压，损耗大、成本高；
#     电压太低 → 大功率设备电流巨大，线缆要很粗、损耗也大。
#   所以工程上做"分层"：大功率走高压（700V）、小功率走低压（48V），
