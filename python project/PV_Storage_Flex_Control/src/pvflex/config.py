# 余电上网（把用不完的光伏卖给电网）的单价。
# ⚠️ 一致性约束（重要）：上网价必须 ≤ 最低零售价（谷段 0.420），否则“谷时买 0.420 /
#    上网卖更高价”会形成经济上的套利窗口，使调度成本函数对净交换量 g 变为凹函数——
#    此时 LP 松弛（无买卖互斥 Binary）与精确 MILP 不再等价，且 LP 会发散。
