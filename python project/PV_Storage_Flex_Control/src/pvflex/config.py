#    凸、LP==MILP。
#    注：本园区真实账单的“光伏结算单”上网结算综合单价曾达 ≈0.8479 元/kWh（含市场化
#    交易/补贴），但该值与谷段零售价 0.420 构成非法套利，本模型采用“净计量等价”简化
#    （自发自用省零售价、余电按燃煤基准价上网）。若要严格使用 0.8479，须改用 MILP 并加
#    买卖互斥 Binary（见 dispatch.solve_dispatch），列入论文未来工作/敏感性讨论。
#
# 【上面这段话在说什么？用大白话解释】
#   假设"买电 4 毛、卖电 8 毛"，那么聪明人马上会发现：
#   谷时段狂买电、转手卖出去，一度净赚 4 毛，跟储能、光伏都没关系 —— 纯套利。
#   这种"凭空赚钱"的最优解在数学上叫"凹函数"，会让求解器算出一个
#   物理上不可能实现的答案（同时大量买和大量卖）。
#   所以必须设定"卖价 ≤ 最低买价"这条约束，把套利窗口关掉，
