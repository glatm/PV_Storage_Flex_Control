# ---- 3.3 单位电能碳排放因子（kgCO2 / kWh，按时段不同）----
# ✅ 已用【福建省真实公开数据】校准，来源：生态环境部、国家统计局《关于发布
#    2023 年电力二氧化碳排放因子的公告》——福建省省级电网平均因子 = 0.4211 kgCO2/kWh
#    （福建因核电[宁德/福清]、水电占比高，显著低于全国均值 0.5306、华东区域 0.5500）。
# 下面曲线锚定省级均值 0.4211，并按福建电源结构做物理合理的“时变性”浮动
# （这正是研究方向3强调的“单位电能碳排放量的时变性”）：
#   · 夜间负荷低谷 + 核电可调度调峰 → 碳排略低于均值；
#   · 傍晚 17-21 点用电高峰、火电顶峰 → 碳排略高于均值。
# 年均值 ≈ 0.42 kgCO2/kWh，与官方省级值一致。
#
# 【"碳因子的时变性"到底指什么？（方向3的核心创新点之一）】
#   传统做法：全年所有时段都用同一个碳因子（比如都用 0.4211），
#             那么"少买一度电"在任何时候减的碳都一样多。
#   本项目的做法：承认不同时段电网里的电"干净程度"不同 ——
#             夜里核电多、碳因子低；傍晚火电顶峰、碳因子高。
#   这样一来，"傍晚少买一度电"减的碳就比"夜里少买一度电"多。
#   优化器因此会倾向于把储能放电安排在傍晚 —— 这正是"能-碳协同"的体现，
#   也是本项目区别于"只看电费"的传统调度的关键。
CARBON_FACTOR_24H = [
    0.391, 0.389, 0.381, 0.379, 0.379, 0.386,   # 0-5 点（夜间核电主导，偏低）
    0.396, 0.406, 0.416, 0.419, 0.426, 0.436,   # 6-11 点
    0.446, 0.446, 0.439, 0.439, 0.446, 0.466,   # 12-17 点
    0.476, 0.469, 0.441, 0.421, 0.411, 0.401,   # 18-23 点（傍晚峰段火电顶高）
]
# 把“碳排(kg)”折算成“钱(元)”的权重：参考碳交易价，约 0.05 元/kgCO2。
# 这样“电费”和“碳成本”就能加到一起，成为一个统一的“能—碳”目标。
#
# 【这就是"能-碳目标函数"的实现方式】
#   目标 = 电费(元) + 碳价权重(元/kg) × 碳排(kg)
#   改大这个权重 = "更看重减碳"，改小 = "更看重省钱"。
#   敏感性分析结果：调这个权重对"省钱"几乎没影响（5.32%~5.46%），
#   但对"减碳"影响明显（3.10%→4.59%）—— 说明两个目标基本不冲突，可以兼顾。
CARBON_PRICE_YUAN_PER_KG = 0.05

# 两个小工具函数：给定小时 h(0-23)，返回该时段的电价 / 碳因子。
# 作用：避免别处代码反复写 GRID_BUY_PRICE_24H[hour % 24] 这种容易写错的索引。
def grid_price_at(hour):
    """返回第 hour 小时（0-23）的买电价（元/kWh）。

    参数
    ----
    hour : int
        小时数。填 0~23 之外的数也能处理（见下面 % 24 的说明）。

    返回
    ----
    float : 该小时的买电价（元/kWh）
    """
    # int(hour) 保证传进来小数也不会报错；% 24 是"取余数"：
    #   24 % 24 = 0，25 % 24 = 1 …… 这样即使传 25 也能正确映射回第 1 点，
    #   传 -1 会得到第 23 点。是个防止"越界报错"的小保险。
    return GRID_BUY_PRICE_24H[int(hour) % 24]

def carbon_factor_at(hour):
    """返回第 hour 小时（0-23）的碳排放因子（kgCO2/kWh）。

    参数
    ----
    hour : int
        小时数（0~23，超出范围会自动绕回）。

    返回
    ----
    float : 该小时的电网碳因子（kgCO2/kWh）
    """
    return CARBON_FACTOR_24H[int(hour) % 24]


