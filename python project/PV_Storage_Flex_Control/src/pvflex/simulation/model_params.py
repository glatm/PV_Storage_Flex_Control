# 【这个文件解决什么问题】
#   本工程（方案 B/方向3）以“项目数据分析 + 能-碳调控”为主，并不做电路仿真。
#   下面这些常量来自你的 Simulink 模型 PV_Microgrid_700V.slx，
#   把它们列在这里只是作为“课题背景”，让你看代码时知道系统在说什么。
#   它们不会参与数据分析计算，只是给人看的“字典”。
#
#   如果你以后想做方案 C（动态仿真），这些就是你要用到的真参数。
#
# 【⚠️ 为什么不在这里做电路仿真？】
#   电路仿真（Simulink）和本项目做的事情是"两个层次"：
#     · Simulink 层：毫秒级的电压电流波形，验证变换器控制环是否稳定 →
#                    这是你 700V 模型 Day1-17 已完成的工作。
#     · 本项目层：小时级的电量/电价/碳排，回答"该充多少电、省多少钱" →
#                    这是经济调度问题，不需要微秒级时间步长。
#   两者靠"参数一致性"衔接（比如母线电压 700V 两边要一样），
#   但不能混在一个程序里跑 —— 时间尺度差 6 个数量级。
#
# 【关于下面为什么大量写 None】
#   这些参数的真实数值藏在 .slx 文件里的模块属性中，需要打开 MATLAB 才能读出来。
#   放在这里写 None（而不是随便编一个数）是【刻意为之】：
#   写个假数字容易被后来的人当成真值用，写 None 则一眼就知道"还没填"。
# =============================================================================

# ---- 电压等级 ----
BUS_VOLTAGE_V = 700.0        # 直流母线标称电压 700 V（系统核心母线）
OUTPUT_VOLTAGE_V = 400.0     # 负载侧经 Buck 变换后的输出电压 400 V

# ---- 参考电压（控制器里用来比较的目标值）----
# "参考值"就是控制系统里"我想要达到的目标"。控制器不断把实测值跟参考值比，
# 有偏差就调整开关管的占空比，把电压拉回参考值 —— 这就是"闭环控制"。
VREF_PV = None               # PV 侧参考电压（模型里 Vref_pv 模块，具体数值在 .slx 中）
VREF_OUT = None              # 输出侧参考电压（模型里 Vref_out，对应 400 V）

# ---- 控制相关增益（来自模型里的 Gain 模块）----
K_DROOP = None               # 下垂控制系数（K_droop）：用于多源并联时的功率分配
# 下垂控制的作用：当光伏、储能、电网多个电源并联供电时，
# 用"电压略微下降"作为信号来分配各自出多少力（像几个人抬轿子自动分力）。
G12_BOOST = None             # Boost 变换器增益 G12_Boost
G12_BUCK = None              # Buck 变换器增益 G12_Buck
# Boost = 升压变换器（把低压升到 700V 母线），Buck = 降压变换器（把 700V 降到 400V）。

# ---- 光照（辐照度）常数 ----
IR_CONST = None              # 光照常数 Ir_Const：仿真里用来把“标幺光照”换算成物理值
# "标幺"（per-unit）是电力系统的常见做法：把物理量除以一个基准值变成 0~1 的无量纲数，
# 仿真时先按标幺值给光照（比如 0.8），再乘上 Ir_Const 还原成真实的 W/m²。

# ---- 占空比开环初值（Constant 模块）----
# 占空比 = 开关管在一个周期里"开"的时间比例，0~1 之间（比如 0.5 就是一半时间导通）。
# "开环初值"就是仿真开始那一刻先给的值，之后由闭环控制接管调整。
D_BOOST_OPEN = None          # Boost 开环占空比 D_Boost_Open
D_BUCK_OPEN = None           # Buck 开环占空比 D_Buck_Open

# ---- 小贴士：怎么看这些参数的真实数值？----
# 上面很多写成 None，是因为它们具体数值藏在 .slx 的模块参数里，
# 不是一眼能看出来的。想知道真实值，可以在 MATLAB 里打开模型后运行：
#   get_param('PV_Microgrid_700V/Vref_out', 'Value')   % 取出某个模块的参数值
# 把取到的数填到上面对应的 None 位置即可。
#
# 【提取出来的参数别直接覆盖原值，最好在旁边写个来源注释】
#   例如：VREF_OUT = 400.0   # 2026-09-14 从 slx 取，模块 Vref_out
#   这样半年后你还能知道这个数是怎么来的、该不该信。
#
# 已知结论（来自之前的模型统计）：
#   开环母线电压 699.76 V，纹波 0.016%，共 193 个模块，已完成三环闭环 + MPPT。
#   关键信号示波器：V_bus(母线700V)、V_pv(PV侧)、I_load(负载电流)、
#                   V_out(负载400V)、CS_bus_load(母线电流/短路保护电流)。
#   ▲ "三环闭环 + MPPT"是这套模型的完成度标志：
