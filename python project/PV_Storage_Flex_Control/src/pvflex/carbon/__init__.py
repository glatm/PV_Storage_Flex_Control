# pvflex/carbon —— 碳排放计算子包
# -----------------------------------------------------------------------------
# 【新手看这里】这个包专门算"用电对应的二氧化碳(CO₂)"。
#   简单说：从电网买 1 度电 ≈ 排了一定量的 CO₂；自己用太阳能发电 ≈ 少排。
#   所以调度策略如果让园区多用自己的电、少买电网的电，碳排就低。
#
# 【⚠️ 一个特别容易搞混的点：电本身不"含碳"】
#   "一度电排多少碳"这个数（碳因子）不是电的属性，
#   而是【当时电网里在发电的那些电厂平均有多干净】。
#   夜里核电多 → 碳因子低；傍晚火电顶峰 → 碳因子高。
#   所以本项目用的是"逐小时碳因子"，而不是一个全年固定值。
#   这也是研究方向3强调的"碳的时变性"，是本项目区别于传统调度的关键之一。
#
# 【核心文件】
#   carbon.py  ——  grid_carbon_of_buy = 买电碳排
#                   net_grid_carbon     = 净碳排（买电减上网，更能反映真实贡献）
#                   carbon_intensity    = 碳强度（每度电排多少，用于效率对比）
#                   annual_carbon_summary = 全年粗略换算（给外行看量级用）
# -----------------------------------------------------------------------------
